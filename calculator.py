# Урок 1. Калькулятор одним файлом.
#
# Это отправная точка. Весь код лежит в одном файле, функций пока нет.
# На уроке 2 мы разнесём его по модулям и пакетам, на уроке 3 научим
# не падать от плохого ввода.

# input() всегда возвращает строку, даже если человек ввёл цифры.
# float() превращает строку в число с точкой. Без него "2" + "3" дало бы "23".
a = float(input("Введите первое число: "))
b = float(input("Введите второе число: "))

# .strip() убирает пробелы по краям (легко поймать лишний пробел при вводе)
# .lower() приводит к нижнему регистру, чтобы "Сложение" и "СЛОЖЕНИЕ" тоже подошли
#
# ВНИМАНИЕ, здесь живёт баг с прошлого занятия.
# Если написать .upper(), получится "СЛОЖЕНИЕ", а сравниваем мы с "сложение".
# Совпадения не будет НИКОГДА, программа молча дойдёт до конца и ничего не выведет.
operation = input("Введите операцию (сложение, вычитание, умножение, деление): ").strip().lower()

if operation == "сложение":
    result = a + b
elif operation == "вычитание":
    result = a - b
elif operation == "умножение":
    result = a * b
elif operation == "деление":
    result = a / b
else:
    # Без этой ветки при опечатке программа тоже молчала бы.
    # Пустой вывод почти всегда означает, что забыли else.
    result = "Неизвестная операция"

# f-строка: то, что в фигурных скобках, подставляется в текст.
# Ближайший аналог из JS — шаблонная строка с ${}.
print(f"Результат: {result}")

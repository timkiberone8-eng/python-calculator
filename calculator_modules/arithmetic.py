#
# Модуль в Python — это просто файл с расширением .py. Никакой особой
# разметки не нужно: создал файл, положил в него функции, и его уже можно
# импортировать. Аналог из фронтенда — обычный файл, из которого делают export.
#
# Зачем: в calculator.py вся арифметика была вперемешку с вводом-выводом.
# Теперь считает один файл, а спрашивает пользователя другой.


def add(x, y):
    """Возвращает сумму двух чисел"""
    # Строка в тройных кавычках сразу после def называется docstring.
    # Это не комментарий: её видно через help(add) и во всплывающей
    # подсказке редактора. Комментарий с # доступен только тому, кто
    # открыл сам файл.
    return x + y


def subtract(x, y):
    """Возвращает разность двух чисел"""
    return x - y


def multiply(x, y):
    """Возвращает произведение двух чисел"""
    return x * y


def divide(x, y):
    """Возвращает частное двух чисел. Деление на ноль вызывает ошибку"""
    # Делим честно, без проверки на ноль внутри функции.
    #
    # Раньше здесь стояло if y != 0, а иначе возвращался текст
    # "Ошибка: деление на ноль". Так делать не надо: текст это
    # обычное значение, а не ошибка. ZeroDivisionError при этом
    # не возникает вовсе, и except для него не сработает никогда.
    #
    # Теперь ошибку бросает сам Python, а ловит её except в main().
    return x / y

def power(base, exponent):
    """Возвращает результат возведения в степень"""
    # ВНИМАНИЕ: в методичке в этом месте опечатка, там написано
    # "return base  exponent" без оператора. Это не код, при запуске
    # будет SyntaxError: invalid syntax.
    # Возведение в степень в Python — две звёздочки.
    return base ** exponent


def square_root(x):
    """Возвращает квадратный корень числа"""
    # Импорт внутри функции — рабочий приём, но нетипичный.
    # Обычно все импорты собирают наверху файла, чтобы сразу было
    # видно, от чего файл зависит. Здесь оставлено как в методичке.
    from math import sqrt
    return sqrt(x)

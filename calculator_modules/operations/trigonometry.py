# math — модуль из стандартной поставки Python. Ставить ничего не нужно,
# он уже есть. Аналогия с фронтендом: как встроенный Math в JS,
# только его надо явно импортировать.

import math


def sin(x):
    """Возвращает синус угла в радианах"""
    # Важно проговорить на занятии: аргумент в РАДИАНАХ, не в градусах.
    # Из градусов переводят так: math.radians(90)
    return math.sin(x)


def cos(x):
    """Возвращает косинус угла в радианах"""
    return math.cos(x)


def tan(x):
    """Возвращает тангенс угла в радианах"""
    return math.tan(x)

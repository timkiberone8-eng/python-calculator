# Урок 2, шаг 1. main.py — точка входа программы.
#
# Теперь файл, который разговаривает с человеком, и файл, который считает,
# это разные файлы. main.py ничего не умеет считать, он только спрашивает,
# вызывает нужную функцию и печатает ответ.

# Импорт: из модуля arithmetic, который лежит в папке calculator_modules,
# взять четыре функции. Точка означает "внутри".
from calculator_modules.arithmetic import add, subtract, multiply, divide


def main():
    print("Добро пожаловать в калькулятор!")
    a = float(input("Введите первое число: "))
    b = float(input("Введите второе число: "))
    operation = input("Введите операцию (сложение, вычитание, умножение, деление): ").strip().lower()

    if operation == "сложение":
        result = add(a, b)
    elif operation == "вычитание":
        result = subtract(a, b)
    elif operation == "умножение":
        result = multiply(a, b)
    elif operation == "деление":
        result = divide(a, b)
    else:
        result = "Неизвестная операция"

    print(f"Результат: {result}")


# Эта строка запускает main() только если файл запустили напрямую
# командой "python main.py". Если этот же файл кто-то импортирует
# как модуль, main() сам не сработает.
# Без неё программа запускалась бы при каждом импорте — частая причина
# странностей у новичков.
if __name__ == "__main__":
    main()

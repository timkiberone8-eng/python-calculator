# CSV (Comma Separated Values) — строки таблицы, значения через запятую.
# Открывается Excel и Google Таблицами, а читается обычным текстом.

import csv

# --- запись ---------------------------------------------------------------

# ЛОВУШКА WINDOWS, проверена запуском. newline="" обязателен.
# Без него модуль csv пишет \r\n, Windows превращает его в \r\r\n,
# и в файле появляется пустая строка после каждой настоящей.
# Проверено: две записанные строки читаются обратно как ЧЕТЫРЕ,
# каждая вторая — пустой список [].
with open("books.csv", "w", newline="", encoding="utf-8") as file:
    writer = csv.writer(file)
    writer.writerow(["Название", "Автор", "Год"])       # строка-заголовок
    writer.writerow(["Гарри Поттер", "Джоан Роулинг", 1997])
    writer.writerow(["1984", "Джордж Оруэлл", 1949])

# writerow пишет ОДНУ строку из списка значений.
# Числа можно передавать как числа: csv сам превратит их в текст.

# --- чтение ---------------------------------------------------------------

print("--- всё, что лежит в books.csv ---")
with open("books.csv", "r", encoding="utf-8") as file:
    reader = csv.reader(file)
    for row in reader:
        # row — это СПИСОК строк, не одна строка.
        # Поэтому print(row) печатает его со скобками и кавычками.
        print(row)

print("--- то же самое, но по-человечески ---")
with open("books.csv", "r", encoding="utf-8") as file:
    reader = csv.reader(file)
    next(reader)        # перескочить строку-заголовок
    for title, author, year in reader:
        print(f"{title} — {author}, {year} год")

# Важное про типы: из CSV всё приходит ТЕКСТОМ. Год 1949 записали числом,
# а прочитали строкой "1949". Если его надо сравнивать или складывать,
# нужен int(year) — и вот тут прилетит ValueError, если в файле мусор.

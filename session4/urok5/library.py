# Задание целиком — PROJECT.md рядом. Шаг 1 делаем на занятии вместе,
# шаги 2 и 3 — дома, в своём репозитории.
#
# Отличие от «Моей библиотеки» (урок 4): там каждая книга сразу уходила
# строкой в файл. Здесь книги живут в памяти, в списке, и каждая книга —
# словарь. Файла на этом шаге нет вообще: закрыл программу — книги
# пропали. Так и должно быть, файл появится на шаге 3.

# Вся библиотека — один список. На старте пустой.
library = []


def add_book(title, author, year, genre):
    """Добавляет одну книгу в библиотеку."""
    # Книга — словарь: все данные одной книги лежат вместе, под своими
    # именами. С четырьмя отдельными списками (названия, авторы, годы,
    # жанры) хватило бы одной ошибки в номере, чтобы книга получила
    # чужого автора.
    book = {
        "title": title,
        "author": author,
        "year": year,
        "genre": genre,
    }
    library.append(book)


def show_books():
    """Печатает все книги с номерами."""
    # Пустая библиотека должна сказать «пусто», а не молчать:
    # молчание выглядит как поломка.
    if not library:
        print("Библиотека пуста.")
        return

    print("Книги в библиотеке:")
    # enumerate(library, 1) выдаёт пары (номер, книга), нумерация с единицы
    for i, book in enumerate(library, 1):
        # К полю словаря обращаемся по ключу: book['title'].
        # Внутри f-строки кавычки одинарные, а снаружи двойные: в Python
        # до версии 3.12 одинаковые кавычки обрывали строку раньше времени.
        print(f"{i}. {book['title']} — {book['author']}, {book['year']}, {book['genre']}")


def main():
    while True:
        print("\n1. Добавить книгу")
        print("2. Показать все книги")
        print("3. Выход")
        choice = input("Выбери пункт: ").strip()

        if choice == "1":
            title = input("Название: ")
            author = input("Автор: ")
            year = input("Год: ")
            genre = input("Жанр: ")
            add_book(title, author, year, genre)
            print("Книга добавлена.")
        elif choice == "2":
            show_books()
        elif choice == "3":
            # Файла пока нет, поэтому всё добавленное сейчас пропадёт.
            # Проверь: запусти снова и выбери пункт 2 — библиотека пуста.
            print("До свидания! Книги не сохранены: файл появится на шаге 3.")
            break       # единственный выход из while True
        else:
            print("Нет такого пункта. Введи 1, 2 или 3.")


if __name__ == "__main__":
    main()

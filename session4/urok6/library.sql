-- year теперь INTEGER, а не текст, как в CSV: база сама проверит,
-- что год — число.
CREATE TABLE books (
    id SERIAL PRIMARY KEY,
    title TEXT,
    author TEXT,
    year INTEGER,
    genre TEXT
);


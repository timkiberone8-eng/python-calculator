# Урок 4, шаг 1. Чтение текстового файла.
#
# Запускать ИЗ ПАПКИ urok4:
#     cd urok4
#     python read_example.py
#
# ЛОВУШКА, проверена запуском. Если запустить из корня проекта командой
# "python urok4/read_example.py", программа упадёт:
#     FileNotFoundError: [Errno 2] No such file or directory: 'example.txt'
# Потому что open() ищет файл относительно ТЕКУЩЕЙ папки терминала,
# а не относительно папки, где лежит скрипт. Это важное отличие от import:
# import ищет рядом со скриптом, open() — там, где ты стоишь в терминале.
# Проверить, где стоишь: pwd (Git Bash) или cd без аргументов (cmd).

# Способ 1: прочитать файл целиком.
with open("example.txt", "r", encoding="utf-8") as file:
    content = file.read()
    print(content)

# with — безопасный способ открыть файл: по выходу из блока Python
# закроет файл сам, даже если внутри случилась ошибка. Без with пришлось
# бы писать file.close(), и при ошибке файл остался бы открытым.
#
# "r" — режим чтения (read). Файл должен существовать.
# encoding="utf-8" — кодировка. Без неё на школьных машинах Windows берёт
# cp1251, и русский текст либо ломается, либо файл не читается вовсе.

print("--- то же самое, но построчно ---")

# Способ 2: построчно. Так читают большие файлы: в память попадает
# одна строка, а не весь файл сразу.
with open("example.txt", "r", encoding="utf-8") as file:
    for line in file:
        # strip() убирает пробелы и невидимый символ перевода строки \n
        # на конце. Без него print добавит второй перевод строки,
        # и между строками появятся пустые.
        print(line.strip())

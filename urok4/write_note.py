# Урок 4, шаг 2. Запись в файл: режимы "w" и "a".
#
# Запускать из папки urok4:
#     python write_note.py
#
# Файл note.txt в репозитории не лежит: его создаёт эта программа.
# Запусти дважды и посмотри, что изменилось.

# "w" — write. Файл создаётся, если его нет, и ПОЛНОСТЬЮ ПЕРЕЗАПИСЫВАЕТСЯ,
# если он есть. Старое содержимое исчезает без предупреждения — это самая
# частая потеря данных у новичков.
with open("note.txt", "w", encoding="utf-8") as file:
    file.write("Сегодня мы учились работать с файлами!\n")

# "a" — append. Дописывает в конец, старое не трогает.
with open("note.txt", "a", encoding="utf-8") as file:
    file.write("А это вторая строка.\n")

# \n на конце обязателен: write() не добавляет перевод строки сам,
# в отличие от print(). Без \n всё склеится в одну длинную строку.

# Упражнение из методички: спросить заметку у пользователя и дописать её.
note = input("Введите свою заметку: ")
with open("note.txt", "a", encoding="utf-8") as file:
    file.write(note + "\n")

print("--- что теперь в файле note.txt ---")
with open("note.txt", "r", encoding="utf-8") as file:
    print(file.read())


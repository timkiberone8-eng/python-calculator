--
--   INSERT INTO users (name, age) VALUES ("Аня", 21);
--   ERROR:  column "Аня" does not exist
-- Двойные кавычки в SQL означают имя столбца, а не строку.
--
--   INSERT INTO users (name, age) VALUES ('Петя', 'двадцать');

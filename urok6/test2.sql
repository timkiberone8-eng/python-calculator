-- Урок 6: первые команды PostgreSQL.
--
-- Это конспект занятия, а не скрипт для запуска целиком: команды вводятся
-- в SQL Shell (psql) по одной, по ходу урока. Строки с двумя минусами —
-- комментарии, psql их пропускает.
--
-- Как войти: Пуск → «SQL Shell (psql)», на четыре вопроса Enter
-- (сервер localhost, база postgres, порт 5432, пользователь postgres),
-- потом пароль postgres. Пароль при вводе не печатается, так и должно быть.
-- Выйти: \q
--
-- Команды двух видов:
--   \l  \c  \dt                     — команды самого psql, точка с запятой не нужна;
--   CREATE  INSERT  SELECT  DROP    — язык SQL, в конце обязательна точка с запятой.
-- Забыл точку с запятой — psql ждёт продолжения, и приглашение postgres=#
-- меняется на postgres-#. Допиши ; и нажми Enter.


-- Шаг 1. Какие базы уже есть.
-- После установки их три: postgres, template0, template1.
\l

-- Шаг 2. Новая база. Она пустая.
CREATE DATABASE test2;

-- Шаг 3. Подключаемся к ней. Приглашение сменится на test2=#,
-- и всё, что создаём дальше, будет лежать внутри test2.
\c test2
